CREATE TABLE material_reference_catalogue (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    alloy_grade VARCHAR(80) NOT NULL UNIQUE,
    material_family VARCHAR(80) NOT NULL,
    condition_name VARCHAR(100) NOT NULL,
    density_g_cm3 DECIMAL(10,4) NOT NULL,
    nominal_tensile_mpa DECIMAL(12,2) NOT NULL,
    nominal_yield_mpa DECIMAL(12,2) NOT NULL,
    nominal_elongation_percent DECIMAL(8,2) NOT NULL,
    typical_application VARCHAR(255) NOT NULL,
    source_title VARCHAR(255) NOT NULL,
    source_url VARCHAR(700) NOT NULL,
    source_note VARCHAR(700) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

